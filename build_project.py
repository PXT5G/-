            '        """Read CPU/RAM utilization using Linux procfs with safe fallbacks."""\n'
            '        cpu_percent = self._read_cpu_percent()\n'
            '        ram_percent = self._read_ram_percent()\n'
            '        return cpu_percent, ram_percent\n'
