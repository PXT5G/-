            '    @staticmethod\n'
            '    def _read_cpu_percent() -> float:\n'
            '        """Approximate CPU pressure from load average."""\n'
            '        try:\n'
            '            load_1m = os.getloadavg()[0]\n'
            '            cpu_count = os.cpu_count() or 1\n'
            '            return min((load_1m / cpu_count) * 100, 100)\n'
            '        except OSError:\n'
            '            return 0.0\n'
            '\n'
            '    @staticmethod\n'
            '    def _read_ram_percent() -> float:\n'
            '        """Read RAM usage from /proc/meminfo."""\n'
            '        try:\n'
            '            meminfo = Path("/proc/meminfo").read_text(encoding="utf-8")\n'
            '        except OSError:\n'
            '            return 0.0\n'
            '\n'
            '        values: dict[str, float] = {}\n'
            '        for line in meminfo.splitlines():\n'
            '            key, _, rest = line.partition(":")\n'
            '            if key in {"MemTotal", "MemAvailable"}:\n'
            '                values[key] = float(rest.strip().split()[0])\n'
            '\n'
            '        total = values.get("MemTotal", 0)\n'
            '        available = values.get("MemAvailable", 0)\n'
            '        if total <= 0:\n'
            '            return 0.0\n'
            '        return max(0.0, min(((total - available) / total) * 100, 100.0))\n'
